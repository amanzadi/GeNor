"""Write docs/cli.md, docs/mcp.md and docs/data-sources.md from the code (run: uv run python scripts/gen_cli_docs.py)."""

from pathlib import Path

import click
import typer

from genor.cli import app

ROOT = Path(__file__).resolve().parents[1]


def walk(cmd: click.Command, path: list[str], out: list[str]) -> None:
    ctx = click.Context(cmd, info_name=" ".join(path), terminal_width=100)
    if hasattr(cmd, "list_commands"):
        if len(path) > 1:
            out.append(f"## `{' '.join(path)}`\n\n{(cmd.help or '').strip()}\n")
        for name in cmd.list_commands(ctx):
            walk(cmd.get_command(ctx, name), [*path, name], out)
        return
    params = []
    for p in cmd.params:
        if getattr(p, "param_type_name", "") == "argument":
            params.append(f"- `{p.name.upper()}`{' (one or more)' if p.nargs == -1 else ''}")
        else:
            default = "" if p.default in (None, False, ()) or p.is_flag and not p.default else f" (default: `{p.default}`)"
            names = ", ".join(f"`{o}`" for o in p.opts + list(p.secondary_opts))
            params.append(f"- {names}: {p.help or ''}{default}")
    out.append(f"### `{' '.join(path)}`\n\n{(cmd.help or '').strip()}\n\n" + "\n".join(params) + "\n")


def main() -> None:
    cli = typer.main.get_command(app)
    out = ["# CLI reference\n",
           "Generated from the code by `scripts/gen_cli_docs.py`. Every command accepts `--json` "
           "(also the default when stdout is not a terminal). Exit codes: 0 ok, 2 actionable error, "
           "3 a decision for the human is needed, 1 unexpected failure.\n"]
    walk(cli, ["genor"], out)
    (ROOT / "docs/cli.md").write_text("\n".join(out))


def mcp_docs() -> None:
    import asyncio
    import inspect

    from genor.mcp_server import METHODS, mcp

    async def tools():
        return await mcp.list_tools()

    out = ["# MCP tools\n",
           "Generated by `scripts/gen_cli_docs.py`. Start the server with `genor mcp` (stdio). "
           "Analyses run as background jobs: tools wait up to `wait_seconds` (max 50, under Codex's "
           "60 s default tool timeout) and otherwise return a `job_id` for `job_status` / `job_result`. "
           "Relative paths resolve against the workspace: `$GENOR_WORKDIR`, else the server's working "
           "directory (`~/genor-workspace` when that is `/`).\n"]
    for t in sorted(asyncio.run(tools()), key=lambda t: t.name):
        params = t.parameters.get("properties", {})
        req = set(t.parameters.get("required", []))
        ps = ", ".join(f"`{k}`" + ("" if k in req else "?") for k in params)
        out.append(f"## `{t.name}`({ps})\n\n{inspect.cleandoc(t.description or '')}\n")
    out.append("## `run_analysis` methods\n\n| method | CLI | params |\n|---|---|---|")
    for m, (path, _, params) in METHODS.items():
        out.append(f"| `{m}` | `genor {' '.join(path)}` | {params.removeprefix('params: ')} |")
    (ROOT / "docs/mcp.md").write_text("\n".join(out) + "\n")


def sources_docs() -> None:
    import tomllib

    src = tomllib.loads((ROOT / "src/genor/sumstats/sources.toml").read_text())
    out = ["# Where to find GWAS summary statistics\n",
           "Generated from `src/genor/sumstats/sources.toml` (also `genor sumstats sources`). GeNor "
           "never downloads GWAS: you download the file, accept the provider's terms, and give GeNor "
           "the local path. Checked 2026-11-25; services change.\n"]
    for k, v in src.items():
        out.append(f"## {v['name']} (`{k}`)\n\n- URL: {v['url']}" + (f"\n- FTP: {v['ftp']}" if v.get("ftp") else "")
                   + f"\n- Access: {v['access']}\n- Format: {v.get('formats', '')}\n- Build: {v.get('build', '')}"
                   + f"\n- Good for: {v.get('good_for', '')}\n- Cite: {v['citation']}\n")
    (ROOT / "docs/data-sources.md").write_text("\n".join(out))


if __name__ == "__main__":
    main()
    mcp_docs()
    sources_docs()
